async function seed() {
  await sql`    
        CREATE TABLE recipes (
            id SERIAL PRIMARY KEY,
            name TEXT NOT NULL,
            ingredients JSONB NOT NULL,
            tags JSONB NOT NULL,
            short_description TEXT,
            rating DECIMAL(2,1),
            prep_time_minutes INTEGER,
            servings INTEGER,
            calorie INTEGER,
            protein INTEGER,
            carbs INTEGER,
            fats INTEGER,
            thumbnail TEXT,
            instructions JSONB NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    `;

  for (const item of RECIPES) {
    await sql`
    INSERT INTO recipes (
      id,
      name,
      ingredients,
      tags,
      short_description,
      rating,
      prep_time_minutes,
      servings,
      calorie,
      protein,
      carbs,
      fats,
      thumbnail,
      instructions
    )
    VALUES (
      ${item.id},
      ${item.name},
      ${JSON.stringify(item.ingredients)},
      ${JSON.stringify(item.tags)},
      ${item.shortDescription},
      ${item.rating},
      ${item.prepTimeMinutes},
      ${item.servings},
      ${item.calorie},
      ${item.protein},
      ${item.carbs},
      ${item.fats},
      ${item.thumbnail},
      ${JSON.stringify(item.instructions)}
    )
  `;
  }

  console.log(`Seed complete inserted ${RECIPES.length}`);
}

seed().catch((error) => {
  console.log("Seed failed", error);
  process.exit(1);
});
